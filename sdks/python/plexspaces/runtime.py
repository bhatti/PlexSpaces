# PlexSpaces Runtime
#
# Generates the WIT interface wrapper for actor classes decorated with @actor.
# This bridges the gap between the Pythonic SDK API and the componentize-py
# WIT bindings.
#
# Supports multiple @actor classes in one module via Erlang-style ApplicationSpec:
# The framework passes {"actor_id": "...", "actor_type": "...", "declaration_name": "..."}
# in init config. The wrapper selects the correct class from declaration_name
# or actor_id prefix matching.

"""
Runtime support for PlexSpaces actors.

This module provides:
- Wrapper generation for WIT interface compatibility
- State serialization/deserialization
- Message dispatch
- Multi-actor support (multiple @actor classes in one WASM module)

The generated wrapper implements the WIT actor interface:
    interface actor {
        init: func(config-json: string) -> string;
        handle: func(from-actor: string, msg-type: string, payload-json: string) -> string;
        get-state: func() -> string;
        set-state: func(state-json: string) -> string;
    }

## Multi-Actor Support

When a module contains multiple @actor classes, the wrapper selects the
class from the init config in priority order:

1. ``config["declaration_name"]`` — the child declaration role from
   ``app-config.toml`` / ``ActorSpawnSpec.role``.
2. Prefix match on the normalized ``actor_id`` against declaration and class
   aliases (e.g. ``data-worker-0`` matches ``data-worker``).
3. ``ACTOR_ROLES`` aliases embedded at build time when provided.
"""

import json
from typing import Type, Any, List, Dict, Optional

from .decorators import (
    get_state_dict,
    set_state_dict,
    dispatch_message,
    init_actor,
    _sanitize_payload_for_wasm,
    _desanitize_from_wasm,
    _has_float,
)


def normalize_role_actor_id(actor_id: str) -> str:
    """
    Normalize runtime actor IDs to the logical child/base ID used by ACTOR_ROLES.

    Supported inputs:
    - child form: ``worker-0:my-app@node-1`` -> ``worker-0``
    - canonical form: ``01ABC//worker-0::my-app@node-1`` -> ``worker-0``
    - bare form: ``worker-0`` -> ``worker-0``
    """
    if not actor_id:
        return ""
    if "//" in actor_id:
        return actor_id.split("//", 1)[0]
    if ":" in actor_id:
        return actor_id.split(":", 1)[0]
    return actor_id


def _class_name_aliases(class_name: str) -> List[str]:
    """Return stable snake_case and kebab-case aliases for a class name."""
    snake = ""
    kebab = ""
    for i, ch in enumerate(class_name):
        if ch.isupper() and i > 0:
            snake += "_"
            kebab += "-"
        snake += ch.lower()
        kebab += ch.lower()

    aliases = [snake]
    if snake != kebab:
        aliases.append(kebab)
    if snake.endswith("_actor"):
        trimmed = snake[: -len("_actor")]
        if trimmed:
            aliases.append(trimmed)
            aliases.append(trimmed.replace("_", "-"))
    return list(dict.fromkeys(alias for alias in aliases if alias))


def build_class_alias_map(
    actor_classes: List[Type], actor_roles: Optional[Dict[str, Type]] = None
) -> Dict[str, Type]:
    """Build the alias map used for multi-actor dispatch."""
    class_map: Dict[str, Type] = {}

    if actor_roles:
        for role, cls in actor_roles.items():
            if cls not in actor_classes:
                continue
            normalized = role.replace("-", "_")
            class_map[normalized] = cls
            class_map[normalized.replace("_", "-")] = cls

    for cls in actor_classes:
        for alias in _class_name_aliases(cls.__name__):
            class_map.setdefault(alias, cls)

    return class_map


def generate_wrapper(
    actor_classes: List[Type], module_name: str, actor_roles: Optional[Dict[str, Type]] = None
) -> str:
    """
    Generate the WIT interface wrapper code for one or more actor classes.

    When multiple classes are provided, the wrapper selects the class from the
    init config in priority order: ``declaration_name`` exact match, prefix
    match on normalized ``actor_id``, then ``actor_type`` exact match.

    Args:
        actor_classes: List of @actor decorated classes (at least one)
        module_name: Name of the module containing the actor classes
        actor_roles: Optional declaration-name to actor-class mapping from ACTOR_ROLES

    Returns:
        Python source code for the wrapper
    """
    if not actor_classes:
        raise ValueError("No @actor classes provided")

    class_names = [cls.__name__ for cls in actor_classes]
    imports = ", ".join(class_names)
    default_class = class_names[0]
    class_map = build_class_alias_map(actor_classes, actor_roles)

    # Build lines for the generated wrapper (no indentation tricks)
    lines = [
        "# AUTO-GENERATED by PlexSpaces SDK",
        "# DO NOT EDIT - regenerate with: plexspaces-py build",
        "",
        "import json",
        "from wit_world import exports",
        f"from {module_name} import {imports}",
        "from plexspaces.decorators import (",
        "    get_state_dict, set_state_dict, dispatch_message, init_actor,",
        "    _sanitize_payload_for_wasm, _desanitize_from_wasm, _has_float,",
        "    payload_from_request_json,",
        ")",
        "",
        "def _normalize_role_actor_id(actor_id: str) -> str:",
        '    """Normalize runtime actor IDs to logical child/base IDs."""',
        "    if not actor_id:",
        '        return ""',
        '    if "//" in actor_id:',
        '        return actor_id.split("//", 1)[0]',
        '    if ":" in actor_id:',
        '        return actor_id.split(":", 1)[0]',
        "    return actor_id",
        "",
    ]

    # Class map for multi-actor support.
    # Selection priority in _select_class:
    #   1. config["declaration_name"] — ChildSpec.role / ActorSpawnSpec.role
    #   2. exact or prefix match on actor_id against declaration/class aliases
    #   3. config["actor_type"] — shared behavior class when it uniquely maps
    if len(actor_classes) == 1:
        lines.append(f"_actor_class = {default_class}")
        lines.append("_CLASS_MAP = {}")
    else:
        lines.append(f"_actor_class = {default_class}  # default")
        lines.append("")
        lines.append("# Auto-generated class map: declaration aliases and class aliases -> class")
        lines.append("_CLASS_MAP = {")
        for alias, cls in class_map.items():
            lines.append(f'    "{alias}": {cls.__name__},')
        lines.append("}")

    lines.extend([
        "",
        "# Actor instance (created on first init)",
        "_instance = None",
        "",
        "",
        "def _select_class(config):",
        '    """Select actor class from init config.',
        "    Priority:",
        '    1. declaration_name — ChildSpec.role / ActorSpawnSpec.role passed by the framework',
        '    2. exact or prefix match on normalized actor_id against declaration/class aliases',
        '    3. config["actor_type"] — ChildSpec.actor_type for single-role behavior classes',
        '    """',
        "    global _actor_class",
        "    if not isinstance(config, dict) or not _CLASS_MAP:",
        "        return _actor_class",
        "    # 1. declaration_name — framework passes ChildSpec.role directly",
        '    decl_name = config.get("declaration_name", "").replace("-", "_")',
        "    if decl_name:",
        "        if decl_name in _CLASS_MAP:",
        "            return _CLASS_MAP[decl_name]",
        "        for key, cls in _CLASS_MAP.items():",
        '            if key.endswith(f"_{decl_name}") or key.endswith(f"-{decl_name}"):',
        "                return cls",
        "    # 2. exact or prefix match on actor_id",
        '    actor_id = _normalize_role_actor_id(config.get("actor_id", ""))',
        "    if actor_id:",
        '        actor_id = actor_id.replace("-", "_")',
        "        if actor_id in _CLASS_MAP:",
        "            return _CLASS_MAP[actor_id]",
        "        for prefix, cls in sorted(_CLASS_MAP.items(), key=lambda x: -len(x[0])):",
        "            if actor_id.startswith(prefix):",
        "                return cls",
        "    # 3. actor_type — shared behavior class fallback",
        '    actor_type = config.get("actor_type", "").replace("-", "_")',
        "    if actor_type and actor_type in _CLASS_MAP:",
        "        return _CLASS_MAP[actor_type]",
        "    return _actor_class",
        "",
        "",
        f'class Actor(exports.Actor):',
        f'    """WIT interface wrapper (supports {", ".join(class_names)})."""',
        "",
        "    def _decode(self, data):",
        '        """Decode WIT payload (list<u8>) to str. Accepts bytes or str."""',
        "        if isinstance(data, (bytes, bytearray)):",
        "            return data.decode('utf-8')",
        "        return str(data) if data else ''",
        "",
        "    def init(self, config):",
        '        """Initialize the actor with optional config."""',
        "        global _instance, _actor_class",
        "        try:",
        "            config_json = self._decode(config)",
        "            config = json.loads(config_json) if config_json else {}",
        "            _actor_class = _select_class(config)",
        "            _instance = _actor_class()",
        "            if config:",
        "                init_actor(_instance, config)",
        "        except Exception as e:",
        '            return f"ERROR: {e}"',
        "",
        "    def handle(self, from_actor: str, msg_type: str, payload):",
        '        """Handle incoming message."""',
        "        global _instance",
        "        if _instance is None:",
        '            return json.dumps({"error": "Actor not initialized"}).encode("utf-8")',
        "",
        "        try:",
        "            payload_json = self._decode(payload)",
        '            payload = payload_from_request_json(payload_json or "")',
        "            result = dispatch_message(_instance, from_actor, msg_type, payload)",
        "",
        "            if isinstance(result, str):",
        '                return result.encode("utf-8")',
        "            # json.dumps handles floats natively as JSON numbers.",
        "            # Do NOT sanitize floats to strings here -- that corrupts",
        "            # inter-actor ask() responses (receivers get strings where",
        "            # they expect numbers, causing 'float + str' TypeError).",
        "            # Float sanitization is only needed in get_state() for",
        "            # checkpoint persistence (reversed by _desanitize_from_wasm",
        "            # in set_state).",
        '            return json.dumps(result).encode("utf-8")',
        "        except Exception as e:",
        '            return json.dumps({"error": str(e)}).encode("utf-8")',
        "",
        "    def get_state(self):",
        '        """Get actor state as JSON bytes."""',
        "        global _instance",
        "        if _instance is None:",
        '            return b"{}"',
        "",
        "        try:",
        "            state = get_state_dict(_instance)",
        "            state_safe = _sanitize_payload_for_wasm(state)",
        '            return json.dumps(state_safe).encode("utf-8")',
        "        except Exception as e:",
        '            return json.dumps({"error": str(e)}).encode("utf-8")',
        "",
        "    def set_state(self, state_data):",
        '        """Restore actor state from JSON bytes."""',
        "        global _instance",
        "        if _instance is None:",
        "            _instance = _actor_class()",
        "",
        "        try:",
        "            state_json = self._decode(state_data)",
        "            state = json.loads(state_json)",
        "            # Recursively restore stringified numbers back to numeric types.",
        "            # get_state sanitizes floats to strings for WASM JSON safety;",
        "            # _desanitize_from_wasm reverses this for lists, dicts, and scalars.",
        "            state = _desanitize_from_wasm(state)",
        "            set_state_dict(_instance, state)",
        '            return ""',
        "        except Exception as e:",
        '            return f"ERROR: {e}"',
    ])

    return "\n".join(lines)


def create_actor_module(user_module_path: str, output_path: str = None) -> str:
    """
    Create a wrapped actor module from a user's actor file.

    Args:
        user_module_path: Path to the user's Python file with @actor class(es)
        output_path: Optional output path (defaults to {name}_wrapper.py)

    Returns:
        Path to the generated wrapper file
    """
    import importlib.util
    import os

    # Load the user's module
    module_name = os.path.splitext(os.path.basename(user_module_path))[0]
    spec = importlib.util.spec_from_file_location(module_name, user_module_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    # Find ALL @actor decorated classes (preserving definition order)
    actor_classes = []
    for name in dir(module):
        obj = getattr(module, name)
        if isinstance(obj, type) and hasattr(obj, '_plexspaces_is_actor'):
            actor_classes.append(obj)

    if not actor_classes:
        raise ValueError(f"No @actor decorated class found in {user_module_path}")

    actor_roles = getattr(module, "ACTOR_ROLES", None)

    # Generate wrapper
    wrapper_code = generate_wrapper(actor_classes, module_name, actor_roles=actor_roles)

    # Write to output file
    if output_path is None:
        output_path = os.path.join(
            os.path.dirname(user_module_path),
            f"{module_name}_actor.py"
        )

    with open(output_path, 'w') as f:
        f.write(wrapper_code)

    return output_path
